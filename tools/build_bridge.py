"""Build the bridge firmware with arduino-cli.

    python tools/build_bridge.py                  # normal build
    python tools/build_bridge.py fallback-test    # temporary hotspot fallback test build
    python tools/build_bridge.py bench-open       # temporary bench build without settings login

Builds firmware/bridge/ for the ESP32 Dev Module with the same toolchain and
partition scheme as the OTA loader, so the image can be uploaded over Wi-Fi.

Variants:
    normal         build/bridge/
    fallback-test  build/bridge-fallback-test/. Joins a network that does not
                   exist, so the hotspot opens; without an OTA upload it boots
                   the previous image after 10 minutes. Never leave it installed.
    bench-open     build/bridge-bench-open/. Settings page and API without
                   password, version ends in -BENCH; boots the previous image
                   after 8 hours of operating time, counted across restarts.
                   Bench only, for unattended tests.

The variant is selected by a generated header, firmware/bridge/bridge_variant.h
(ignored by Git, removed after the build), not by a compiler flag: compiler
flags also apply to the Arduino core and force a full core rebuild. Build
folders live outside the sketch; a build folder inside the sketch is picked up
as sketch source. A build takes between 1 and 5 minutes (S104, S105 in
docs/research/sources.md).

The firmware carries the public default logins from config.h
(docs/manual/user-manual.md#logins); no credentials file is needed.

Prints the toolchain, the duration, the image size and any warning or error
from the sketch files. Nothing is uploaded.
"""

import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKETCH = ROOT / "firmware" / "bridge"
VARIANT_HEADER = SKETCH / "bridge_variant.h"
FQBN = "esp32:esp32:esp32:PartitionScheme=min_spiffs,CPUFreq=160"  # 160 MHz: fewer heap dips than 80 MHz (S199); 240 MHz runs too hot (S187)
SKETCH_FILES = tuple(f.name for f in SKETCH.iterdir() if f.suffix in (".ino", ".h"))  # warnings from these are shown
VARIANTS = {
    "normal": (ROOT / "build" / "bridge", None),
    "fallback-test": (ROOT / "build" / "bridge-fallback-test", "FALLBACK_TEST"),
    "bench-open": (ROOT / "build" / "bridge-bench-open", "BENCH_OPEN"),
}


def core_version() -> str:
    out = subprocess.run(["arduino-cli", "core", "list"], capture_output=True, text=True, check=True).stdout
    match = re.search(r"^esp32:esp32\s+(\S+)", out, re.MULTILINE)
    return match.group(1) if match else "unknown"


def cli_version() -> str:
    out = subprocess.run(["arduino-cli", "version"], capture_output=True, text=True, check=True).stdout
    match = re.search(r"Version:\s*(\S+)", out)
    return match.group(1) if match else "unknown"


def build(name: str) -> int:
    build_dir, flag = VARIANTS[name]
    VARIANT_HEADER.unlink(missing_ok=True)
    if flag:
        VARIANT_HEADER.write_text(f"// Generated by tools/build_bridge.py; ignored by Git.\n#pragma once\n#define {flag}\n", encoding="utf-8")
    cmd = ["arduino-cli", "compile", "--fqbn", FQBN, "--warnings", "all", "--build-path", str(build_dir), str(SKETCH)]
    print(f"[{name}] arduino-cli {cli_version()}, esp32 core {core_version()}, {FQBN}", flush=True)
    print(f"[{name}] building in {build_dir.relative_to(ROOT).as_posix()}/ ...", flush=True)
    start = time.monotonic()
    result = subprocess.run(cmd, capture_output=True, text=True)
    seconds = time.monotonic() - start
    log = result.stdout + result.stderr
    sketch_lines = [
        line
        for line in log.splitlines()
        if any(name in line for name in SKETCH_FILES) and ("warning" in line or "error" in line)
    ]
    sizes = [line for line in log.splitlines() if line.startswith(("Sketch uses", "Global variables use"))]

    if result.returncode != 0:
        print(f"[{name}] FAILED after {seconds:.0f} s", flush=True)
        print("\n".join(sketch_lines) or log[-2000:], flush=True)
        return 1
    print(f"[{name}] ok in {seconds:.0f} s", flush=True)
    for line in sizes + sketch_lines:
        print(f"[{name}] {line}", flush=True)
    image = build_dir / "bridge.ino.bin"
    if image.exists():
        print(f"[{name}] image {image.relative_to(ROOT).as_posix()}, {image.stat().st_size} bytes", flush=True)
    return 0


def main(argv: list[str]) -> int:
    name = argv[0] if argv else "normal"
    if name not in VARIANTS or len(argv) > 1:
        print(f"Usage: python tools/build_bridge.py [{' | '.join(VARIANTS)}]")
        return 2
    try:
        return build(name)
    finally:
        # Leave no variant selected, so the Arduino IDE builds the normal firmware.
        VARIANT_HEADER.unlink(missing_ok=True)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
