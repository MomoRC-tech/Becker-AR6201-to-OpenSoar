def f(v):
    return f"{v:.4f}".rstrip("0").rstrip(".")


def stub(part, pin, px, py, dx, net_segments, net):
    """Short wire from a pin with a net label at its free end."""
    ex = px + dx
    rot = ' rot="R180"' if dx < 0 else ""
    net_segments.setdefault(net, []).append(
        f'<segment><pinref part="{part}" gate="G$1" pin="{pin}"/>'
        f'<wire x1="{f(px)}" y1="{f(py)}" x2="{f(ex)}" y2="{f(py)}" width="0.1524" layer="91"/>'
        f'<label x="{f(ex)}" y="{f(py)}" size="1.778" layer="95"{rot}/></segment>'
    )


def build():
    parts, instances, nets = [], [], {}
    # Part names and wire descriptions as sheet text: Fusion's import does not show symbol >NAME/>VALUE.
    texts = [(t, gx * G, gy * G, size) for t, gx, gy, size in NOTES]
    for name, value, net, gx, gy in WIRES:
        x, y = gx * G, gy * G
        parts.append(f'<part name="{name}" library="bridge" deviceset="WIRE" device="" value="{escape(value)}"/>')
        instances.append(f'<instance part="{name}" gate="G$1" x="{f(x)}" y="{f(y)}"/>')
        stub(name, "P", x + G, y, 3 * G, nets, net)
        texts.append((f"{name}: {value}", x + 10 * G, y - 0.6, 1.778))
    for name, value, n1, n2, gx, gy in RESISTORS:
        x, y = gx * G, gy * G
        parts.append(f'<part name="{name}" library="bridge" deviceset="R" device="" value="{value}"/>')
        instances.append(f'<instance part="{name}" gate="G$1" x="{f(x)}" y="{f(y)}"/>')
        stub(name, "1", x - 2 * G, y, -3 * G, nets, n1)
        stub(name, "2", x + 2 * G, y, 3 * G, nets, n2)
        texts.append((f"{name} {value}", x - 2 * G, y + 1.6, 1.778))

    texts = "".join(f'<text x="{f(x)}" y="{f(y)}" size="{size}" layer="97">{escape(t)}</text>' for t, x, y, size in texts)
    layers = "".join(
        f'<layer number="{n}" name="{nm}" color="{c}" fill="1" visible="yes" active="yes"/>' for n, nm, c in LAYERS
    )
    nets_xml = "".join(f'<net name="{escape(n)}" class="0">{"".join(s)}</net>' for n, s in sorted(nets.items()))
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE eagle SYSTEM "eagle.dtd">
<eagle version="9.6.2">
<drawing>
<settings><setting alwaysvectorfont="no"/><setting verticaltext="up"/></settings>
<grid distance="0.1" unitdist="inch" unit="inch" style="lines" multiple="1" display="yes" altdistance="0.01" altunitdist="inch" altunit="inch"/>
<layers>{layers}</layers>
<schematic xreflabel="%F%N/%S.%C%R" xrefpart="/%S.%C%R">
<description>Bridge perfboard: RX divider, pull-ups, ground point, 3.3 V / 5 V distribution.</description>
<libraries>
{LIBRARY}
</libraries>
<attributes/>
<variantdefs/>
<classes><class number="0" name="default" width="0" drill="0"/></classes>
<parts>
{chr(10).join(parts)}
</parts>
<sheets>
<sheet>
<plain>{texts}</plain>
<instances>
{chr(10).join(instances)}
</instances>
<busses/>
<nets>
{nets_xml}
</nets>
</sheet>
</sheets>
</schematic>
</drawing>
</eagle>
"""


def build_board():
    """Matching board: all parts placed unrouted in a row, connections as airwires.
    Fusion's import needs a .sch/.brd pair; placement on the perfboard comes later."""
    elements, signals = [], {}
    x = 0.0
    for name, value, net, _, _ in WIRES:
        elements.append(f'<element name="{name}" library="bridge" package="WIREPAD" value="{escape(value)}" x="{f(x)}" y="0"/>')
        signals.setdefault(net, []).append(f'<contactref element="{name}" pad="1"/>')
        x += 2 * G
    x = 0.0
    for name, value, n1, n2, _, _ in RESISTORS:
        elements.append(f'<element name="{name}" library="bridge" package="R0204/7" value="{value}" x="{f(x + 3 * G)}" y="{f(-4 * G)}"/>')
        signals.setdefault(n1, []).append(f'<contactref element="{name}" pad="1"/>')
        signals.setdefault(n2, []).append(f'<contactref element="{name}" pad="2"/>')
        x += 5 * G
    layers = "".join(
        f'<layer number="{n}" name="{nm}" color="{c}" fill="1" visible="yes" active="yes"/>' for n, nm, c in LAYERS
    )
    sig = "".join(f'<signal name="{escape(n)}" class="0">{"".join(c)}</signal>' for n, c in sorted(signals.items()))
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!DOCTYPE eagle SYSTEM "eagle.dtd">
<eagle version="9.6.2">
<drawing>
<settings><setting alwaysvectorfont="no"/><setting verticaltext="up"/></settings>
<grid distance="0.1" unitdist="inch" unit="inch" style="lines" multiple="1" display="yes" altdistance="0.01" altunitdist="inch" altunit="inch"/>
<layers>{layers}</layers>
<board>
<plain/>
<libraries>
{LIBRARY}
</libraries>
<attributes/>
<variantdefs/>
<classes><class number="0" name="default" width="0" drill="0"/></classes>
<elements>
{chr(10).join(elements)}
</elements>
<signals>
{sig}
</signals>
</board>
</drawing>
</eagle>
"""


if __name__ == "__main__":
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    for path, text in ((OUT, build()), (OUT[:-4] + ".brd", build_board())):
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote", os.path.normpath(path))
