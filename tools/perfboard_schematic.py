"""Generate the perfboard schematic as an EAGLE 9 .sch file for Fusion Electronics.

Usage (from the repository root):  python tools/perfboard_schematic.py
Writes cad/perfboard/bridge-perfboard.sch. Open it in Fusion (Upload into the
project, or File > Open), check it, and commit script and .sch together.

Scope (docs/hardware/housing.md, design rules): minimal board. Only the resistor,
power and ground nets land on the perfboard; wires are soldered directly into
its holes. Each wire landing is a one-pad part "W<n>" whose value names the far
end. Nets connect by name (net labels), not by drawn wires.
Net plan: docs/hardware/wiring.md and docs/hardware/power.md.
"""
